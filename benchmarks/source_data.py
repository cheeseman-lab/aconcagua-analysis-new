def _aggregate_heatmap_tsv(path: Path, value_col: str, new_col: str) -> pd.DataFrame:
    """Load a well+tile heatmap TSV and aggregate to per-well mean."""
    df = pd.read_csv(path, sep="\t")
    # Rename value column if needed
    if value_col in df.columns and value_col != new_col:
        df = df.rename(columns={value_col: new_col})
    elif value_col not in df.columns:
        # Use whatever non-well/tile column exists
        val_cols = [c for c in df.columns if c not in ("well", "tile")]
        if val_cols:
            df = df.rename(columns={val_cols[0]: new_col})
    return df.groupby("well", as_index=False)[new_col].mean().round(4)


def load_fig2b() -> pd.DataFrame:
    """Fig2b: two sections in one sheet.
    Columns: section | well | fraction_single_gene | gene_name | cell_count
    Top section: per-well fraction of cells mapping to single gene (plate 1).
    Bottom section: per-gene cell count across all plate 1 wells.
    """
    import glob

    # Top: well-level heatmap
    well_raw = _aggregate_heatmap_tsv(
        BRIEFLOW_OUT / "sbs/eval/mapping/P-1__cell_mapping_heatmap_one.tsv",
        "fraction of cells mapping to 1 gene symbols",
        "fraction_single_gene",
    )
    well_rows = [
        {"section": "well_mapping_fraction", "well": r["well"],
         "fraction_single_gene": r["fraction_single_gene"], "gene_name": "", "cell_count": ""}
        for _, r in well_raw.iterrows()
    ]

    # Bottom: per-gene cell count from plate 1 SBS cells parquets
    parquet_paths = sorted(glob.glob(str(BRIEFLOW_OUT / "sbs/parquets/P-1_W-*__cells.parquet")))
    gene_counts: dict[str, int] = {}
    for p in parquet_paths:
        counts = pd.read_parquet(p, columns=["gene_symbol_0"])["gene_symbol_0"].dropna().value_counts()
        for gene, count in counts.items():
            gene_counts[gene] = gene_counts.get(gene, 0) + int(count)

    gene_rows = [
        {"section": "per_gene_cell_count", "well": "", "fraction_single_gene": "",
         "gene_name": gene, "cell_count": count}
        for gene, count in sorted(gene_counts.items(), key=lambda x: -x[1])
    ]

    blank = [{"section": "", "well": "", "fraction_single_gene": "", "gene_name": "", "cell_count": ""}]
    return pd.DataFrame(well_rows + blank + gene_rows)


