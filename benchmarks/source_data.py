def load_supp6c() -> pd.DataFrame:
    """SuppFig6c: confusion matrix from classifier JSON report."""
    json_path = (
        BRIEFLOW_OUT / "classifier/classifier/run_20260112_172222/models/multiclass_xgb_k50"
        / "multiclass_xgb_k50_classification_report.json"
    )
    with open(json_path) as f:
        report = json.load(f)

    mitotic_support = int(report["0"]["support"])
    interphase_support = int(report["1"]["support"])
    mitotic_recall = report["0"]["recall"]
    interphase_recall = report["1"]["recall"]
    mitotic_precision = report["0"]["precision"]
    interphase_precision = report["1"]["precision"]

    mitotic_tp = round(mitotic_recall * mitotic_support)
    mitotic_fn = mitotic_support - mitotic_tp
    interphase_tp = round(interphase_recall * interphase_support)
    interphase_fn = interphase_support - interphase_tp

    rows = [
        {"true_class": "Mitotic",     "predicted_class": "Mitotic",     "count": mitotic_tp},
        {"true_class": "Mitotic",     "predicted_class": "Interphase",  "count": mitotic_fn},
        {"true_class": "Interphase",  "predicted_class": "Interphase",  "count": interphase_tp},
        {"true_class": "Interphase",  "predicted_class": "Mitotic",     "count": interphase_fn},
    ]
    cm_df = pd.DataFrame(rows)

    # Summary stats
    total = mitotic_support + interphase_support
    accuracy = report.get("accuracy", (mitotic_tp + interphase_tp) / total)
    summary = pd.DataFrame([{
        "metric": "overall_accuracy", "value": round(accuracy, 4),
    }, {
        "metric": "mitotic_recall", "value": round(mitotic_recall, 4),
    }, {
        "metric": "mitotic_precision", "value": round(mitotic_precision, 4),
    }, {
        "metric": "interphase_recall", "value": round(interphase_recall, 4),
    }, {
        "metric": "interphase_precision", "value": round(interphase_precision, 4),
    }])

    blank = pd.DataFrame([["", "", ""]], columns=cm_df.columns)
    label = pd.DataFrame([["Summary", "", ""]], columns=cm_df.columns)
    summary_aligned = summary.reindex(columns=cm_df.columns)
    return pd.concat([cm_df, blank, label, summary_aligned], ignore_index=True)


