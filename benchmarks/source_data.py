def _load_corr_matrix_for_clusters(
    npz_path: Path,
    brieflow_cluster_tsv: Path,
    funk_cluster_tsv: Path,
    highlight_brieflow_clusters: set,
    highlight_funk_clusters: set,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Load NPZ and return two DataFrames with split-diagonal correlation matrices.

    Returns:
        fig5c_df: genes ordered by Brieflow cluster (rows=genes, cols=gene_name + corr values)
        fig5d_df: same data reordered by Funk cluster
    """
    npz = np.load(str(npz_path), allow_pickle=True)
    n_genes = int(npz["_n"])
    brieflow_clusters = npz["brieflow_cluster"]  # shape (n_genes,)
    funk_clusters = npz["funk_cluster"]          # shape (n_genes,)
    pca_brieflow = npz["cos_pca_brieflow"]       # shape (n_genes, n_genes)
    feat_funk = npz["cos_feat_funk"]             # shape (n_genes, n_genes)

    # Reconstruct gene names: NPZ genes are sorted(shared_genes)
    # Load brieflow clustering TSV to get all genes and sort alphabetically
    bl_clust = pd.read_csv(brieflow_cluster_tsv, sep="\t")[["gene_symbol_0", "cluster"]]
    fk_clust = pd.read_csv(funk_cluster_tsv, sep="\t")[["gene_symbol", "cluster"]].rename(
        columns={"gene_symbol": "gene_symbol_0", "cluster": "funk_cluster_id"}
    )

    # NPZ gene order = sorted intersection of brieflow + funk genes
    shared_genes = sorted(set(bl_clust["gene_symbol_0"]) & set(fk_clust["gene_symbol_0"]))
    if len(shared_genes) != n_genes:
        print(f"  WARNING: shared_genes={len(shared_genes)} but NPZ _n={n_genes}; using first {n_genes}")
        shared_genes = shared_genes[:n_genes]

    gene_array = np.array(shared_genes)

    # Filter to mito clusters
    bl_mask = np.isin(brieflow_clusters, list(highlight_brieflow_clusters))
    fk_mask = np.isin(funk_clusters, list(highlight_funk_clusters))

    # Fig5c: genes in Brieflow mito clusters, Brieflow-ordered
    bl_idx = np.where(bl_mask)[0]
    bl_order = np.argsort(brieflow_clusters[bl_idx])
    bl_idx_sorted = bl_idx[bl_order]
    bl_genes = gene_array[bl_idx_sorted]
    bl_pca = pca_brieflow[np.ix_(bl_idx_sorted, bl_idx_sorted)]
    bl_feat = feat_funk[np.ix_(bl_idx_sorted, bl_idx_sorted)]

    # Build split-diagonal: upper triangle = Brieflow PCA, lower = Funk raw
    matrix_5c = np.triu(bl_pca) + np.tril(bl_feat, k=-1)
    bl_df = pd.DataFrame(matrix_5c, columns=bl_genes)
    bl_df.insert(0, "brieflow_cluster", brieflow_clusters[bl_idx_sorted])
    bl_df.insert(0, "gene_name", bl_genes)

    # Fig5d: genes in Funk mito clusters, Funk-ordered
    fk_idx = np.where(fk_mask)[0]
    fk_order = np.argsort(funk_clusters[fk_idx])
    fk_idx_sorted = fk_idx[fk_order]
    fk_genes = gene_array[fk_idx_sorted]
    fk_pca = pca_brieflow[np.ix_(fk_idx_sorted, fk_idx_sorted)]
    fk_feat = feat_funk[np.ix_(fk_idx_sorted, fk_idx_sorted)]

    matrix_5d = np.triu(fk_pca) + np.tril(fk_feat, k=-1)
    fk_df = pd.DataFrame(matrix_5d, columns=fk_genes)
    fk_df.insert(0, "funk_cluster", funk_clusters[fk_idx_sorted])
    fk_df.insert(0, "gene_name", fk_genes)

    return bl_df, fk_df


