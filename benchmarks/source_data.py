def load_fig2c():
    """Spot calling comparison with Mann-Whitney p-values."""
    df = pd.read_csv(RESULTS / "spot_calling/benchmark_results.csv")
    df = df.rename(columns={
        "method": "method",
        "total_peaks": "raw_spots_detected",
        "total_reads": "mapped_reads",
        "read_mapping_fraction": "mapping_fraction",
        "1_gene_cells__percent": "gene_mapping_efficiency_pct",
        "1_barcode_cells__percent": "barcode_efficiency_pct",
    })
    main_cols = [
        "plate", "well", "tile", "method",
        "raw_spots_detected", "mapped_reads", "mapping_fraction",
        "barcode_efficiency_pct", "gene_mapping_efficiency_pct",
        "runtime_seconds", "memory_mb",
    ]
    main_cols = [c for c in main_cols if c in df.columns]
    main_df = df[main_cols].copy()

    # Mann-Whitney U p-values for key metrics
    metrics = [
        "raw_spots_detected", "mapped_reads", "mapping_fraction",
        "barcode_efficiency_pct", "gene_mapping_efficiency_pct",
        "runtime_seconds",
    ]
    standard = df[df["method"] == "standard"]
    spotiflow = df[df["method"] == "spotiflow"]
    pval_rows = []
    for m in metrics:
        if m not in df.columns:
            continue
        a = standard[m].dropna()
        b = spotiflow[m].dropna()
        if len(a) > 0 and len(b) > 0:
            stat, p = stats.mannwhitneyu(a, b, alternative="two-sided")
            pval_rows.append({"metric": m, "standard_median": a.median(), "spotiflow_median": b.median(), "mann_whitney_U": stat, "p_value": p})
    pval_df = pd.DataFrame(pval_rows)

    # Return combined: main data, blank separator row, p-values table
    blank = pd.DataFrame([[""] * len(main_df.columns)], columns=main_df.columns)
    label_row = pd.DataFrame([["Mann-Whitney U tests"] + [""] * (len(main_df.columns) - 1)], columns=main_df.columns)
    pval_aligned = pval_df.reindex(columns=main_df.columns)
    return pd.concat([main_df, blank, label_row, pval_aligned], ignore_index=True)


